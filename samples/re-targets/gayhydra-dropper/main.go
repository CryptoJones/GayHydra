// gayhydra-dropper: reverse-engineering training sample.
//
// Behavior: enumerates mounted filesystems from /proc/mounts, filters out
// pseudo-filesystems and read-only mounts, and drops a calling-card file
// (1337.txt) at the root of each remaining mount.
//
// Intended as a Ghidra/GayHydra training target. Strings are XOR-obfuscated
// with a single-byte key so students have something to deobfuscate beyond
// `strings(1)`. The control flow is intentionally straightforward.
//
// SAFE TO RUN AS A NON-ROOT USER: writes will fail on mounts the invoking
// user can't write to, and the program continues past errors rather than
// stopping. As a non-root user on a typical Linux box, this usually only
// writes to $HOME's filesystem and /tmp.
//
// DO NOT RUN AS ROOT unless you're in a throwaway VM. Do not ship the
// compiled binary anywhere it could be mistaken for a real implant.

package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const xorKey byte = 0x5A

// deobfuscate decodes a XOR-obfuscated string. The obfuscated blobs below
// were produced with the same key; see scripts/obfuscate.go for the encoder.
func deobfuscate(b []byte) string {
	out := make([]byte, len(b))
	for i, c := range b {
		out[i] = c ^ xorKey
	}
	return string(out)
}

